def chart_for(lift: str) -> dict:
    """種目名からチャートを返す。BP系はbp_chart、それ以外はsq_dl_chart。"""
    return bp_chart if lift.upper() in ("BP", "BENCH", "BENCH PRESS") else sq_dl_chart


def e1rm(lift: str, weight: float, reps: int, rpe: float) -> float | None:
    """チャート範囲外(reps>15, RPE<2, 刻み外)は None。"""
    chart = chart_for(lift)
    if rpe not in chart or not 1 <= reps <= 15:
        return None
    return weight / chart[rpe][reps - 1]
